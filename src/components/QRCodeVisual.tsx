import React, { useRef } from 'react';
import { QRCodeSVG } from 'qrcode.react';
import { ShieldCheck, Download, Copy, Check, ExternalLink } from 'lucide-react';

interface QRCodeVisualProps {
  value: string;
  size?: number;
  label?: string;
  sublabel?: string;
  lightMode?: boolean;
  showActions?: boolean;
  logoUrl?: string;
}

export const QRCodeVisual: React.FC<QRCodeVisualProps> = ({
  value,
  size = 140,
  label = 'SCAN TO VERIFY STATUS',
  sublabel = 'UAE Government Synced',
  lightMode = true,
  showActions = false,
}) => {
  const [copied, setCopied] = React.useState(false);
  const containerRef = useRef<HTMLDivElement>(null);

  // If value is a bare reference ID (e.g. SAY-1001 or RCP-2026-0981), build full scannable URL
  const origin = typeof window !== 'undefined' ? window.location.origin : 'https://sayem-uae.portal';
  const scannableUrl = value.startsWith('http://') || value.startsWith('https://')
    ? value
    : value.startsWith('RCP-')
    ? `${origin}/?receipt=${encodeURIComponent(value)}#track`
    : `${origin}/?ref=${encodeURIComponent(value)}#track`;

  const handleCopyLink = () => {
    navigator.clipboard.writeText(scannableUrl);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadPNG = () => {
    // Generate a high resolution PNG canvas from the SVG
    const svgEl = containerRef.current?.querySelector('svg');
    if (!svgEl) return;

    const svgData = new XMLSerializer().serializeToString(svgEl);
    const svgBlob = new Blob([svgData], { type: 'image/svg+xml;charset=utf-8' });
    const URL = window.URL || window.webkitURL || window;
    const blobURL = URL.createObjectURL(svgBlob);

    const image = new Image();
    image.onload = () => {
      const canvas = document.createElement('canvas');
      const scale = 3; // 3x for crisp print quality
      canvas.width = size * scale;
      canvas.height = size * scale;
      const ctx = canvas.getContext('2d');
      if (ctx) {
        ctx.fillStyle = '#ffffff';
        ctx.fillRect(0, 0, canvas.width, canvas.height);
        ctx.drawImage(image, 0, 0, canvas.width, canvas.height);
        const pngUrl = canvas.toDataURL('image/png');
        const downloadLink = document.createElement('a');
        downloadLink.href = pngUrl;
        downloadLink.download = `QR_${value.replace(/[^a-zA-Z0-9_-]/g, '_')}.png`;
        document.body.appendChild(downloadLink);
        downloadLink.click();
        document.body.removeChild(downloadLink);
      }
      URL.revokeObjectURL(blobURL);
    };
    image.src = blobURL;
  };

  return (
    <div
      ref={containerRef}
      className={`flex flex-col items-center text-center p-3 rounded-2xl transition-all ${
        lightMode
          ? 'bg-white text-gray-900 border-2 border-gray-900 shadow-sm'
          : 'bg-[#0b1329] text-white border border-white/15 shadow-xl'
      }`}
    >
      {/* Real QR Code generated by qrcode.react library */}
      <div className="relative p-2 bg-white rounded-xl shadow-inner border border-gray-100 flex items-center justify-center">
        <QRCodeSVG
          value={scannableUrl}
          size={size}
          level="H"
          bgColor="#ffffff"
          fgColor="#080e1e"
          marginSize={2}
          imageSettings={{
            src: '/assets/aistudio/WhatsApp_Image_2026-04-18_at_9.28.09_PM_bc31dc09.jpeg',
            x: undefined,
            y: undefined,
            height: Math.round(size * 0.22),
            width: Math.round(size * 0.22),
            excavate: true,
          }}
        />
      </div>

      {/* Verification Subtitle & Ref Code */}
      {label && (
        <div className="mt-2.5 text-center max-w-[180px]">
          <span
            className={`block font-mono font-black text-[9px] uppercase tracking-wider leading-tight ${
              lightMode ? 'text-gray-900' : 'text-[#73e4e8]'
            }`}
          >
            {label}
          </span>
          <span
            className={`block text-[8px] font-mono mt-0.5 truncate ${
              lightMode ? 'text-gray-500' : 'text-gray-400'
            }`}
            title={scannableUrl}
          >
            {value}
          </span>
        </div>
      )}

      {/* Action Buttons for Interactive Modals */}
      {showActions && (
        <div className="flex items-center gap-1.5 mt-3 pt-2.5 border-t border-gray-200 dark:border-white/10 w-full justify-center">
          <button
            type="button"
            onClick={handleCopyLink}
            className={`px-2.5 py-1 rounded-lg text-[10px] font-semibold flex items-center gap-1 cursor-pointer transition-colors ${
              lightMode
                ? 'bg-gray-100 hover:bg-gray-200 text-gray-800'
                : 'bg-white/10 hover:bg-white/20 text-white'
            }`}
            title="Copy Direct Tracking URL"
          >
            {copied ? <Check className="w-3 h-3 text-emerald-500" /> : <Copy className="w-3 h-3" />}
            <span>{copied ? 'Copied' : 'Copy'}</span>
          </button>

          <button
            type="button"
            onClick={handleDownloadPNG}
            className={`px-2.5 py-1 rounded-lg text-[10px] font-semibold flex items-center gap-1 cursor-pointer transition-colors ${
              lightMode
                ? 'bg-[#080d1b] hover:bg-gray-800 text-white'
                : 'bg-[#73e4e8]/20 hover:bg-[#73e4e8]/30 text-[#73e4e8] border border-[#73e4e8]/30'
            }`}
            title="Download QR code as High-Res PNG"
          >
            <Download className="w-3 h-3" />
            <span>Download</span>
          </button>
        </div>
      )}
    </div>
  );
};
